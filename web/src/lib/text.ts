/**
 * 显示层的文本清洗。
 *
 * ## 为什么需要它
 *
 * 语料是 PDF 抽出来的，而 PDF 里的公式往往用**数学字母数字符号**
 * （Mathematical Alphanumeric Symbols, U+1D400–U+1D7FF）排版：
 * 斜体的 `t` 不是 `t`，是 `𝑡`（U+1D461）。这类字符在绝大多数系统字体里
 * 没有字形，浏览器画成一个豆腐块，于是证据卡上出现：
 *
 * ```
 * �𝑡𝑡+1 = 𝐶𝐶(𝑥𝑥𝑡𝑡)𝑥𝑥𝑡𝑡+1 + 𝐷𝐷(𝑥𝑥𝑡𝑡)𝑢𝑢𝑡𝑡
 * ```
 *
 * 读者第一反应是"这个界面坏了"。而真实原因是**语料本身的排版方式**，
 * 界面只是照实渲染。
 *
 * ## 为什么不是整串 NFKC
 *
 * 整串 `normalize("NFKC")` 能把这些字符还原成 ASCII，但会顺带把
 * `m³/d` 变成 `m3/d`、把 `℃` 变成 `°C` —— 前者在这套界面上是**单位**，
 * 掉了上标就不再是同一个单位写法。所以只对数学字母数字区做归一化，
 * 一个字符一个字符地换，其余原样保留。
 *
 * ## 它修不了什么
 *
 * 这**只是显示层的补救**。检索排序仍然被这些符号汤影响 —— 一个"盖层完整性"
 * 的问题，排在前面的证据可能是一页公式。那是入库阶段的问题（分块策略、
 * 是否过滤公式段），不在这一层解决。不要因为界面好看了就以为问题没了。
 */

/** 数学字母数字符号区：𝐀–𝟿（含粗体、斜体、手写体、双线体等变体）。 */
const MATH_ALNUM = /[\u{1D400}-\u{1D7FF}]/gu;

/** U+FFFD 是"解码失败"的占位符，携带零信息，留着只会渲染成豆腐块。 */
const REPLACEMENT_CHAR = /\uFFFD/g;

export function readable(text: string): string {
  return text.replace(MATH_ALNUM, (ch) => ch.normalize("NFKC")).replace(REPLACEMENT_CHAR, "");
}

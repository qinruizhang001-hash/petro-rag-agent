"""
CCUS 全链条运维 Agent（operations）
===================================
与 ``nodes/`` 的区别：``nodes/`` 回答"这个项目有什么风险"（离线评估，一次
一问）；本包回答"现在这条链上发生了什么、要不要叫人、该写什么报告"
（在线运维，连续运行）。

四个 Agent 的分工与**能力边界**：

===============  ================================  ==============================
Agent            输入                              输出
===============  ================================  ==============================
``alarms``       传感器时序 + 阈值注册表            分级告警 + 归因候选 + 处置建议
``condition``    自然语言问句 + 传感器时序          带引用的工况回答
``reports``      告警/统计 + 报告模板               草稿 + 逐数字引用 + 审批状态
``supervisor``   上述三者的产物                     任务拆分 + 冲突清单 + 汇总
===============  ================================  ==============================

三条贯穿全包的硬约束（写在这里，因为它们是设计约束不是实现细节）：

1. **没有出处的阈值不参与判定。** ``Threshold`` 的 ``source`` 为空会直接抛
   ``ValueError``；没配阈值的传感器返回 ``indeterminate``，不是 ``normal``。
   把"不知道"渲染成"正常"是这类系统最危险的一种失败 —— 它不会报错，只会
   让看板一直绿。
2. **归因给候选，不给结论。** 运维误判的代价不对称：漏掉一个真因子的代价
   远大于多列一个假因子。所以 ``attribution`` 是一个**带排除理由的排序列表**，
   每条候选都写明"凭哪几条读数支持"和"凭什么被排除"。
3. **报告里的每个数字都要能回代。** ``reports`` 生成的正文里，数字必须紧跟
   ``[alarm:ID]`` 或 ``[reading:sensor@ts]`` 形式的引用；没有引用的数字在
   出稿前被检查出来，不静默放行。
"""

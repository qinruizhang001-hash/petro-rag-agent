"""
汇总节点的 Prompt 组装（纯字符串，不调模型）
============================================
``aggregate_report`` 里最长、最容易被改坏、又最不需要"执行上下文"的部分就是
这几段 Prompt：角色设定 + 写作硬约束 + 材料拼接。它们原来直接写在节点函数里，
结果是"改一句约束"和"调一次工具"混在同一屏，review 时根本分不清改的是哪类东西。

抽成纯函数之后：
* 约束条目可以被单测直接断言（比如"第 11 条必须要求每句都有出处"）；
* ``aggregate_node.py`` 只剩编排：合并 → 规划 → 执行工具 → 成稿 → 收尾。

注意这里**没有**任何模型调用，也没有任何 I/O —— 传什么字符串进去，就拼出什么
字符串出来。
"""
from __future__ import annotations


def build_system_prompt(file_memory_block: str | None) -> str:
    """角色 + 长期文件记忆 + 写作硬约束。"""
    return f"""你是一个资深的CCUS首席工程师，负责撰写 CO2 地质封存项目的风险评估报告。

{file_memory_block or "（暂无文件记忆）"}

【写作硬性约束】：
1. 如果知识库中没有相关记录，必须直接输出"知识库中无相关记录"。
2. 必须遵循上面「用户画像」中的报告风格偏好（结论先行、分点陈述、数值落地）。
3. **禁止使用"综上所述""总而言之""总的来说"等总结性套话**，直接分点陈述。
4. 如果本次场景与「历史评估记录」中的某次相近，应显式做纵向对比
   （例如"相比上次 250bar/80℃ 的评估，本次压力更高，断层活化风险上升"）。
5. 请分点列出：1. 主要地质封存风险 2. 主要井筒风险 3. 缓解与监测建议。
6. **绝对不要输出 JSON、工具指令或图片 Markdown 路径**，只写正文。
7. 下面给的是**两条并行分支各自产出的结论**（地质 / 井筒）。你的任务是
   **融合**而不是复述：保留两段中的全部数值与判断，去掉重复表述，
   按上面的 1/2/3 结构重新组织。**不要新增两段里没有的结论。**
8. **结论必须是概率性的，不是绝对的。** 凡是来自【不确定性量化结果】的数值，
   必须写成「均值 + 90% 置信区间」的形式（如"密度 1.35 kg/m³，
   90% 置信区间 1.28–1.42"），**禁止只给单一数值**，也禁止写成
   "约为""大约"这类模糊措辞 —— 前者隐瞒了不确定性，后者没有信息量。
9. 风险判断可以带概率，但**概率只能照抄【工具执行结果】或【不确定性量化结果】
   里已有的数字**。工具没算过的风险类型，写"该风险未做概率量化，需现场评估"，
   不要编造百分比，也不要给它配上"100 次蒙特卡洛"之类的来源说明 ——
   实测 7B 会照着示例把 5 类风险各编一个百分数，全部无法溯源。
10. 如果【时间维度提示】里给出了冲突数据，必须采用**最新时间戳**的数值，
   并显式说明引用了哪个时间点、与旧数据差多少；禁止取平均或隐去旧值。
11. **每一句风险判断和建议都必须能在下面【证据】里找到出处。**
    "应做微地震监测""应制定应急预案""应布置监测井"这类通用工程常识，
   证据里没出现就不要写 —— 第 3 节若证据未提供针对性建议，直接写
   "知识库中未提供针对性的缓解/监测建议"。评审按"每个陈述能否被证据支持"
   打分，凭空补的通用段落会直接拉低忠实度。"""


def build_degraded_hint(branch: dict) -> str:
    """缺失分支时，要求报告开头点明"结论不完整"。"""
    degraded_hint = ""
    if branch["degraded"]:
        degraded_hint = (
            "\n【数据完整性警告】：本次缺失以下分支，"
            "请在报告开头用一句话说明结论不完整、需人工复核：\n"
            + "\n".join(f"- {m}" for m in branch["missing"])
            + "\n"
        )
    return degraded_hint


def build_materials(state, branch: dict, personal_context: str) -> str:
    """两阶段共用的材料块：参数 + 两段分支结论 + 时间冲突 + 上一版意见。"""
    degraded_hint = build_degraded_hint(branch)
    # ─── 时间维度冲突：只注入结构化摘要，不重放整段检索结果 ───
    # retrieve 节点已经把完整提示块拼进了 retrieved_knowledge，但终稿刻意
    # 不再读那一整段（省 token）。冲突只有几条，单独带进来代价极小，
    # 而漏掉它会让"优先采用最新数据"这条约束在终稿阶段彻底消失。
    temporal_block = ""
    conflicts = state.get("temporal_conflicts") or []
    if conflicts:
        lines = ["\n【时间维度：检测到同一对象在不同时间点的冲突数据】"]
        for c in conflicts[:5]:
            lines.append(
                f"- {c['message']} → **以 {c['newer']['timestamp']} 的 "
                f"{c['newer']['display']} 为准**"
            )
        lines.append("（禁止取平均；必须说明差异幅度与可能原因）\n")
        temporal_block = "\n".join(lines)
    return f"""【提取的 CCUS 参数】：{state['extracted_params']}
【地质分支结论（LightRAG 图谱证据）】：
{branch['geology']}

【井筒分支结论（ChromaDB 文献证据）】：
{branch['wellbore']}
{degraded_hint}{temporal_block}
{personal_context}
【上一版报告的修改意见】：{state.get('feedback', '无')}"""
